-- Fallar si hay objetos invalidos, pues CREATE OR REPLACE puede dejar errores.
SET SERVEROUTPUT ON
DECLARE
  v_n NUMBER;
  v_t NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_n FROM USER_OBJECTS
  WHERE STATUS='VALID' AND (
    (OBJECT_NAME='FN_EP2_TOTAL_MATRICULAS' AND OBJECT_TYPE='FUNCTION') OR
    (OBJECT_NAME='FN_EP2_CLASIFICAR_ARANCEL' AND OBJECT_TYPE='FUNCTION') OR
    (OBJECT_NAME='PR_EP2_ACTUALIZAR_RESUMEN' AND OBJECT_TYPE='PROCEDURE') OR
    (OBJECT_NAME='PR_EP2_REPORTE_AREA' AND OBJECT_TYPE='PROCEDURE') OR
    (OBJECT_NAME='PKG_EP2_ACADEMICO' AND OBJECT_TYPE='PACKAGE') OR
    (OBJECT_NAME='PKG_EP2_ACADEMICO' AND OBJECT_TYPE='PACKAGE BODY') OR
    (OBJECT_NAME='TRG_EP2_ARANCEL_FILA' AND OBJECT_TYPE='TRIGGER') OR
    (OBJECT_NAME='TRG_EP2_ARANCEL_SENTENCIA' AND OBJECT_TYPE='TRIGGER'));
  IF v_n<>8 THEN
    RAISE_APPLICATION_ERROR(-20210,'Objetos EP2 VALID esperados: 8. Encontrados: '||v_n);
  END IF;
  SELECT COUNT(*) INTO v_t FROM USER_TABLES WHERE TABLE_NAME IN
    ('EP2_RESUMEN_AREA','EP2_AUDITORIA_ARANCEL','EP2_AUDITORIA_SENTENCIA');
  IF v_t<>3 THEN RAISE_APPLICATION_ERROR(-20211,'Faltan tablas auxiliares EP2'); END IF;
  DBMS_OUTPUT.PUT_LINE('OK: 8 objetos validos y 3 tablas complementarias');
END;
/
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM USER_ERRORS
WHERE NAME LIKE '%EP2%' ORDER BY NAME,SEQUENCE;
