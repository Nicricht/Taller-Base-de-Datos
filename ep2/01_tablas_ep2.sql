-- Tablas complementarias EP2: no se modifica ninguna tabla de negocio EP1.
-- Reejecucion no destructiva: solo CREATE si falta la tabla.
DECLARE
  PROCEDURE crear(p_nombre VARCHAR2, p_sql VARCHAR2) IS
    v_num NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_num FROM USER_TABLES WHERE TABLE_NAME=p_nombre;
    IF v_num=0 THEN EXECUTE IMMEDIATE p_sql; END IF;
  END;
BEGIN
  crear('EP2_RESUMEN_AREA', q'[
    CREATE TABLE EP2_RESUMEN_AREA (
      id_area NUMBER PRIMARY KEY,
      nombre_area VARCHAR2(150) NOT NULL,
      total_ofertas NUMBER NOT NULL,
      total_planes NUMBER NOT NULL,
      arancel_promedio NUMBER(12,2),
      fecha_calculo TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT fk_ep2_resumen_area FOREIGN KEY (id_area) REFERENCES AREA_CONOCIMIENTO(id_area),
      CONSTRAINT ck_ep2_totales CHECK (total_ofertas>=0 AND total_planes>=0)
    )]');
  crear('EP2_AUDITORIA_ARANCEL', q'[
    CREATE TABLE EP2_AUDITORIA_ARANCEL (
      id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_plan_oferta NUMBER NOT NULL,
      arancel_anterior NUMBER(10) NOT NULL,
      arancel_nuevo NUMBER(10) NOT NULL,
      usuario_bd VARCHAR2(128) NOT NULL,
      fecha_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
    )]');
  crear('EP2_AUDITORIA_SENTENCIA', q'[
    CREATE TABLE EP2_AUDITORIA_SENTENCIA (
      id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      operacion VARCHAR2(50) NOT NULL,
      usuario_bd VARCHAR2(128) NOT NULL,
      fecha_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
    )]');
END;
/
